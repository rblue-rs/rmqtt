//! Strict lower-layer resource diagnostic, not production enforcement or an RSS cap.
mod client;
mod layers;
use std::{
    alloc::{GlobalAlloc, Layout, System},
    io::{self, Read, Write},
    process::ExitCode,
    sync::atomic::{AtomicBool, AtomicUsize, Ordering},
};
use tungstenite::{
    protocol::{Role, WebSocketConfig},
    Message, WebSocket,
};
struct Counted;
static LIVE: AtomicUsize = AtomicUsize::new(0);
static PEAK: AtomicUsize = AtomicUsize::new(0);
static MAX_REQUEST: AtomicUsize = AtomicUsize::new(0);
static TRACK: AtomicBool = AtomicBool::new(false);
fn added(size: usize) {
    let live = LIVE.fetch_add(size, Ordering::SeqCst) + size;
    if TRACK.load(Ordering::SeqCst) {
        PEAK.fetch_max(live, Ordering::SeqCst);
        MAX_REQUEST.fetch_max(size, Ordering::SeqCst);
    }
}
// SAFETY: forward every pointer/Layout/size unchanged to System. Atomics allocate
// nothing. Counters cover requested active Rust allocations, not allocator internals.
unsafe impl GlobalAlloc for Counted {
    unsafe fn alloc(&self, l: Layout) -> *mut u8 {
        let p = System.alloc(l);
        if !p.is_null() {
            added(l.size());
        }
        p
    }
    unsafe fn alloc_zeroed(&self, l: Layout) -> *mut u8 {
        let p = System.alloc_zeroed(l);
        if !p.is_null() {
            added(l.size());
        }
        p
    }
    unsafe fn dealloc(&self, p: *mut u8, l: Layout) {
        System.dealloc(p, l);
        LIVE.fetch_sub(l.size(), Ordering::SeqCst);
    }
    unsafe fn realloc(&self, p: *mut u8, l: Layout, n: usize) -> *mut u8 {
        let q = System.realloc(p, l, n);
        if !q.is_null() {
            if n >= l.size() {
                added(n - l.size());
            } else {
                LIVE.fetch_sub(l.size() - n, Ordering::SeqCst);
            }
            if TRACK.load(Ordering::SeqCst) {
                MAX_REQUEST.fetch_max(n, Ordering::SeqCst);
            }
        }
        q
    }
}
#[global_allocator]
static ALLOC: Counted = Counted;
const K: usize = 1024;
const BUDGET: usize = 2 * K * K;
#[derive(Clone, Copy)]
enum Case {
    Header,
    Frame,
    Fragments,
    TinyFragments,
    TinyMessages,
    Pings(usize),
}
impl Case {
    fn name(self) -> &'static str {
        match self {
            Self::Header => "header_over_16MiB",
            Self::Frame => "frame_3MiB",
            Self::Fragments => "fragment_total_4MiB",
            Self::TinyFragments => "one_byte_fragments_300000",
            Self::TinyMessages => "one_byte_messages_65536",
            Self::Pings(_) => "blocked_writer_pings",
        }
    }
    fn frames(self) -> usize {
        match self {
            Self::Header | Self::Frame => 1,
            Self::Fragments => 32,
            Self::TinyFragments => 300000,
            Self::TinyMessages => 65536,
            Self::Pings(n) => n + 1,
        }
    }
    fn spec(self, i: usize) -> (u8, usize) {
        match self {
            Self::Header => (0x82, 17 * K * K),
            Self::Frame => (0x82, 3 * K * K),
            Self::Fragments | Self::TinyFragments => {
                let opcode = if i == 0 {
                    2
                } else if i + 1 == self.frames() {
                    0x80
                } else {
                    0
                };
                (
                    opcode,
                    if matches!(self, Self::Fragments) {
                        128 * K
                    } else {
                        1
                    },
                )
            }
            Self::TinyMessages => (0x82, 1),
            Self::Pings(n) => {
                if i < n {
                    (0x89, 125)
                } else {
                    (0x82, 2)
                }
            }
        }
    }
}
// Synthetic independent wire peer: fixed metadata, generated bytes, no payload
// allocations. Writes always WouldBlock, reads continue. No timing or RSS sample.
struct Wire {
    case: Case,
    frame: usize,
    pos: usize,
}
impl Wire {
    fn new(case: Case) -> Self {
        Self {
            case,
            frame: 0,
            pos: 0,
        }
    }
}
impl Read for Wire {
    fn read(&mut self, out: &mut [u8]) -> io::Result<usize> {
        let mut used = 0;
        while used < out.len() && self.frame < self.case.frames() {
            let (opcode, len) = self.case.spec(self.frame);
            let head = if len < 126 {
                2
            } else if len <= 65535 {
                4
            } else {
                10
            };
            let end = if matches!(self.case, Case::Header) {
                head
            } else {
                head + len
            };
            if self.pos == end {
                self.frame += 1;
                self.pos = 0;
                continue;
            }
            out[used] = match self.pos {
                0 => opcode,
                1 => {
                    if len < 126 {
                        len as u8
                    } else if len <= 65535 {
                        126
                    } else {
                        127
                    }
                }
                p if p < head => {
                    if head == 4 {
                        (len as u16).to_be_bytes()[p - 2]
                    } else {
                        (len as u64).to_be_bytes()[p - 2]
                    }
                }
                _ => 0,
            };
            used += 1;
            self.pos += 1;
        }
        if used == 0 {
            Err(io::ErrorKind::WouldBlock.into())
        } else {
            Ok(used)
        }
    }
}
impl Write for Wire {
    fn write(&mut self, _: &[u8]) -> io::Result<usize> {
        Err(io::ErrorKind::WouldBlock.into())
    }
    fn flush(&mut self) -> io::Result<()> {
        Err(io::ErrorKind::WouldBlock.into())
    }
}
#[derive(Debug)]
struct Stats {
    peak: usize,
    max_request: usize,
    released: bool,
    capacity: bool,
    messages: usize,
    ok: bool,
}
fn config(bounded: bool, mutate: bool) -> WebSocketConfig {
    if bounded {
        WebSocketConfig::default()
            .read_buffer_size(8 * K)
            .write_buffer_size(8 * K)
            .max_write_buffer_size(if mutate { usize::MAX } else { 256 * K })
            .max_frame_size(Some(
                if std::env::var_os("WS_PROBE_MUTATE_FRAME").is_some() {
                    16 * K * K
                } else {
                    256 * K
                },
            ))
            .max_message_size(Some(
                if std::env::var_os("WS_PROBE_MUTATE_MESSAGE").is_some() {
                    64 * K * K
                } else {
                    256 * K
                },
            ))
    } else {
        WebSocketConfig::default()
    }
}
fn measure(case: Case, bounded: bool, mutate: bool) -> Stats {
    let baseline = LIVE.load(Ordering::SeqCst);
    PEAK.store(baseline, Ordering::SeqCst);
    MAX_REQUEST.store(0, Ordering::SeqCst);
    TRACK.store(true, Ordering::SeqCst);
    let mut ws =
        WebSocket::from_raw_socket(Wire::new(case), Role::Client, Some(config(bounded, mutate)));
    let target = match case {
        Case::Pings(_) | Case::TinyMessages => case.frames(),
        _ => 1,
    };
    let mut messages = 0;
    let mut capacity = false;
    let mut valid = true;
    for _ in 0..target {
        match ws.read() {
            Ok(Message::Binary(_) | Message::Ping(_)) => messages += 1,
            Err(tungstenite::Error::Capacity(_)) => {
                capacity = true;
                break;
            }
            _ => {
                valid = false;
                break;
            }
        }
    }
    drop(ws);
    TRACK.store(false, Ordering::SeqCst);
    let peak = PEAK.load(Ordering::SeqCst) - baseline;
    let max_request = MAX_REQUEST.load(Ordering::SeqCst);
    let released = LIVE.load(Ordering::SeqCst) == baseline;
    let expected_capacity = matches!(case, Case::Header)
        || (bounded && matches!(case, Case::Frame | Case::Fragments | Case::TinyFragments));
    Stats {
        peak,
        max_request,
        released,
        capacity,
        messages,
        ok: valid
            && released
            && peak <= BUDGET
            && capacity == expected_capacity
            && (capacity || messages == target),
    }
}
fn main() -> ExitCode {
    if std::env::args().any(|a| a == "--client") {
        return client::run();
    }
    if std::env::args().any(|a| a == "--layers") {
        return layers::run();
    }
    let bounded = std::env::args().any(|a| a == "--bounded");
    let mutate = std::env::args().any(|a| a == "--mutate-write");
    println!("scope=lower_library_fixture NOT product cap; proposed tracked budget={BUDGET}; bounded_counterfactual={bounded}; mutate_write={mutate}");
    println!("effective_config={:?}", config(bounded, mutate));
    // Warm thread-local random masking/stdio outside captured object lifetime.
    {
        let mut w = WebSocket::from_raw_socket(Wire::new(Case::Pings(2)), Role::Client, None);
        let _ = w.read();
        let _ = w.read();
    }
    let pings = std::env::var("WS_PROBE_PINGS")
        .ok()
        .map(|s| s.parse::<usize>().unwrap())
        .unwrap_or(32768);
    println!("generated_ping_count={pings}");
    let mut pass = 0;
    for case in [
        Case::Header,
        Case::Frame,
        Case::Fragments,
        Case::TinyFragments,
        Case::TinyMessages,
        Case::Pings(pings),
    ] {
        let s = measure(case, bounded, mutate);
        if s.ok {
            pass += 1;
        }
        println!("{} peak_requested_live={} max_allocation_request={} released={} capacity_error={} messages={} pass={}",case.name(),s.peak,s.max_request,s.released,s.capacity,s.messages,s.ok);
    }
    println!(
        "fixture budget readiness {pass}/6; counterfactual config is NOT installed in rumqttc"
    );
    if pass == 6 {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}
